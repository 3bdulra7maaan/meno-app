-- Meno v1.1: server-enforced content safety, answer reports and Home banners.
-- Additive/non-destructive: no production table or user content is dropped.

create or replace function public.normalize_moderation_text(input_text text)
returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  value text := lower(coalesce(input_text, ''));
begin
  value := regexp_replace(value, '[ً-ٰٟۖ-ۭـ]', '', 'g');
  value := translate(value, 'أإآٱ', 'اااا');
  value := regexp_replace(value, '([ء-ي])\1{2,}', '\1', 'g');
  value := regexp_replace(value, '[^a-z0-9ء-ي]+', ' ', 'g');
  return trim(regexp_replace(value, '\s+', ' ', 'g'));
end;
$$;

create table if not exists public.blocked_words (
  id uuid primary key default gen_random_uuid(),
  word text not null check (char_length(trim(word)) between 2 and 100),
  normalized_word text generated always as (
    public.normalize_moderation_text(word)
  ) stored,
  category text not null default 'other'
    check (category in ('abuse', 'racism', 'spam', 'other')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists blocked_words_normalized_word_idx
  on public.blocked_words(normalized_word);
create index if not exists blocked_words_enabled_idx
  on public.blocked_words(enabled) where enabled;

create table if not exists public.answer_reports (
  id uuid primary key default gen_random_uuid(),
  answer_id uuid not null references public.answers(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (
    reason in ('abuse', 'misleading', 'spam', 'inappropriate', 'other')
  ),
  status text not null default 'open'
    check (status in ('open', 'dismissed', 'actioned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(answer_id, reporter_id)
);

create index if not exists answer_reports_status_created_idx
  on public.answer_reports(status, created_at desc);
create index if not exists answer_reports_answer_idx
  on public.answer_reports(answer_id);

create table if not exists public.home_banners (
  id uuid primary key default gen_random_uuid(),
  image_url text not null check (image_url ~ '^https://'),
  title text not null check (char_length(trim(title)) between 2 and 100),
  short_text text not null default '' check (char_length(short_text) <= 240),
  target_url text check (target_url is null or target_url ~ '^https://'),
  type text not null default 'announcement'
    check (type in ('announcement', 'promotion', 'ad')),
  enabled boolean not null default true,
  display_order integer not null default 0 check (display_order >= 0),
  start_at timestamptz,
  end_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (end_at is null or start_at is null or end_at > start_at)
);

create index if not exists home_banners_public_order_idx
  on public.home_banners(enabled, display_order, start_at, end_at);

create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  object_type text not null
    check (object_type in ('question', 'answer', 'report', 'blocked_word', 'banner')),
  object_id uuid not null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists moderation_actions_created_idx
  on public.moderation_actions(created_at desc);

