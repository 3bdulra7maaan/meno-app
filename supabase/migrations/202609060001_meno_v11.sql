create policy "Admins manage blocked words" on public.blocked_words
for all to authenticated
using (public.is_meno_admin())
with check (public.is_meno_admin());

create policy "Users submit own answer reports" on public.answer_reports
for insert to authenticated
with check (reporter_id = auth.uid());
create policy "Admins read answer reports" on public.answer_reports
for select to authenticated using (public.is_meno_admin());
create policy "Admins update answer reports" on public.answer_reports
for update to authenticated
using (public.is_meno_admin()) with check (public.is_meno_admin());

create policy "Public reads active banners" on public.home_banners
for select to anon, authenticated
using (
  enabled
  and (start_at is null or start_at <= now())
  and (end_at is null or end_at > now())
);
create policy "Admins read all banners" on public.home_banners
for select to authenticated using (public.is_meno_admin());
create policy "Admins insert banners" on public.home_banners
for insert to authenticated with check (public.is_meno_admin());
create policy "Admins update banners" on public.home_banners
for update to authenticated
using (public.is_meno_admin()) with check (public.is_meno_admin());
create policy "Admins delete banners" on public.home_banners
for delete to authenticated using (public.is_meno_admin());

create policy "Admins read moderation history" on public.moderation_actions
for select to authenticated using (public.is_meno_admin());

