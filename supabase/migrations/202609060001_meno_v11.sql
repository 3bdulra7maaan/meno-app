create or replace function public.contains_blocked_content(input_text text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.blocked_words word
    where word.enabled
      and position(
        ' ' || word.normalized_word || ' '
        in ' ' || public.normalize_moderation_text(input_text) || ' '
      ) > 0
  );
$$;

create or replace function public.is_submission_text_allowed(input_text text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select not public.contains_blocked_content(input_text);
$$;

create or replace function public.enforce_allowed_content()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  submitted_text text;
begin
  if tg_table_name = 'questions' then
    submitted_text := concat_ws(' ', new.title, new.body);
  else
    submitted_text := new.body;
  end if;

  if public.contains_blocked_content(submitted_text) then
    raise exception using
      errcode = 'P0001',
      message = 'يرجى تعديل النص، بعض الكلمات المستخدمة غير مسموح بها في Meno.';
  end if;
  return new;
end;
$$;

drop trigger if exists questions_content_safety on public.questions;
create trigger questions_content_safety
before insert or update of title, body on public.questions
for each row execute function public.enforce_allowed_content();

drop trigger if exists answers_content_safety on public.answers;
create trigger answers_content_safety
before insert or update of body on public.answers
for each row execute function public.enforce_allowed_content();

create or replace function public.report_answer(
  answer_id_input uuid,
  reason_input text
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  inserted_count integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if reason_input not in ('abuse', 'misleading', 'spam', 'inappropriate', 'other') then
    raise exception 'Invalid report reason';
  end if;
  if not exists (
    select 1 from public.answers answer
    join public.questions question on question.id = answer.question_id
    where answer.id = answer_id_input
      and not answer.is_hidden
      and question.status = 'approved'
  ) then
    raise exception 'Answer is not available';
  end if;

  insert into public.answer_reports(answer_id, reporter_id, reason)
  values (answer_id_input, auth.uid(), reason_input)
  on conflict (answer_id, reporter_id) do nothing;
  get diagnostics inserted_count = row_count;
  return inserted_count = 1;
end;
$$;

create or replace function public.audit_moderation_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  audit_action text;
  audit_type text := tg_table_name;
begin
  if not public.is_meno_admin() then return new; end if;
  if tg_table_name = 'questions' and old.status is distinct from new.status then
    audit_action := 'status:' || new.status::text;
    audit_type := 'question';
  elsif tg_table_name = 'answers' and old.is_hidden is distinct from new.is_hidden then
    audit_action := case when new.is_hidden then 'hide' else 'restore' end;
    audit_type := 'answer';
  elsif tg_table_name = 'answer_reports' and old.status is distinct from new.status then
    audit_action := 'status:' || new.status;
    audit_type := 'report';
  else
    return new;
  end if;
  insert into public.moderation_actions(
    actor_user_id, object_type, object_id, action
  ) values (auth.uid(), audit_type, new.id, audit_action);
  return new;
end;
$$;

drop trigger if exists questions_moderation_audit on public.questions;
